/**
 * TreeLime starts as a copy of BEAUti (dr.app.treelime): for the same data and model choices its generator must write
 * the same model as BEAUti's, apart from the "Generated by" line. TreeLime's own fixes to the copied generators (the
 * Skygrid gradient blocks and the mixed-effects clock; SkygridGeneratorTest, MixedEffectsClockGeneratorTest) are left
 * out of the configurations compared here, since BEAUti does not have them. The run section differs: BEAUti writes operators and
 * an MCMC chain where TreeLime writes the densities to maximize and a maximizer, so the comparison stops there. Both
 * option models are driven through the same reflective steps, so each configuration is written once.
 */
public class TreeLimeForkIdentityTest extends TestCase {

    private static final String BEAUTI = "dr.app.beauti";
    private static final String TREELIME = "dr.app.treelime";

    private static final String[] COMPONENTS = {
            "components.ancestralstates.AncestralStatesComponentFactory",
            "components.continuous.ContinuousComponentFactory",
            "components.discrete.DiscreteTraitsComponentFactory",
            "components.dollo.DolloComponentFactory",
            "components.linkedparameters.LinkedParameterComponentFactory",
            "components.hpm.HierarchicalModelComponentFactory",
            "components.marginalLikelihoodEstimation.MarginalLikelihoodEstimationComponentFactory",
            "components.sequenceerror.SequenceErrorModelComponentFactory",
            "components.tipdatesampling.TipDateSamplingComponentFactory"
    };

    public TreeLimeForkIdentityTest(String name) {
        super(name);
    }

    // BEAUti's defaults: HKY, strict clock, constant-size coalescent
    public void testDefaults() throws Exception {
        assertSameXML("examples/Data/Primates_two_partition.nex", "<HKYModel", "<strictClockBranchRates", "<constantSize");
    }

    public void testGtrGammaInvariantUncorrelatedClocksYule() throws Exception {
        assertSameXML("examples/Data/Primates_two_partition.nex", "<gtrModel", "<discretizedBranchRates", "<yuleModel",
                new Step("substitutionModels", "setNucSubstitutionModel", "GTR"),
                new Step("substitutionModels", "setGammaHetero", true),
                new Step("substitutionModels", "setInvarHetero", true),
                new Step(UNLINK_CLOCKS),
                new Step("clocks", "setClockType", "UNCORRELATED"),
                new Step("clocks", "setClockDistributionType", "LOGNORMAL"),
                new Step("treePriors", "setNodeHeightPrior", "YULE"));
    }

    // not Skygrid: TreeLime's generator prefixes and places the Skygrid gradient blocks, which BEAUti's does not
    // (SkygridGeneratorTest)
    public void testHmcClockSkyride() throws Exception {
        assertSameXML("examples/Data/Primates_two_partition.nex", "<arbitraryBranchRates", "<gmrfSkyrideLikelihood",
                new Step("clocks", "setClockType", "HMC_CLOCK"),
                new Step("treePriors", "setNodeHeightPrior", "GMRF_SKYRIDE"));
    }

    public void testTipDatesExponentialGrowthRandomLocalClock() throws Exception {
        assertSameXML("examples/Data/Dengue4.env.nex", "<date value=\"1982", "<randomLocalClockModel",
                "<exponentialGrowth",
                new Step(TIP_DATES),
                new Step("substitutionModels", "setGammaHetero", true),
                new Step("clocks", "setClockType", "RANDOM_LOCAL_CLOCK"),
                new Step("treePriors", "setNodeHeightPrior", "EXPONENTIAL"));
    }

    public void testAminoAcidsBirthDeath() throws Exception {
        assertSameXML("examples/Data/YFV.aa.fasta", "<aminoAcidModel", "<birthDeathModel",
                new Step("treePriors", "setNodeHeightPrior", "BIRTH_DEATH"));
    }

    private static final String UNLINK_CLOCKS = "unlinkClocks";
    private static final String TIP_DATES = "tipDates";

    private static class Step {
        final String target;
        final String method;
        final Object value;

        Step(String action) {
            this(action, null, null);
        }

        Step(String target, String method, Object value) {
            this.target = target;
            this.method = method;
            this.value = value;
        }
    }

    private void assertSameXML(String data, String expected, Step... steps) throws Exception {
        assertSameXML(data, new String[]{expected}, steps);
    }

    private void assertSameXML(String data, String expected1, String expected2, Step... steps) throws Exception {
        assertSameXML(data, new String[]{expected1, expected2}, steps);
    }

    private void assertSameXML(String data, String expected1, String expected2, String expected3, Step... steps)
            throws Exception {
        assertSameXML(data, new String[]{expected1, expected2, expected3}, steps);
    }

    // expected: elements that show the configuration took effect
    private void assertSameXML(String data, String[] expected, Step... steps) throws Exception {
        if (!new File(data).exists()) {
            System.err.println("Skipping: " + data + " not found from " + new File(".").getAbsolutePath());
            return;
        }
        String beauti = generate(BEAUTI, data, steps);
        String treeLime = generate(TREELIME, data, steps);
        for (String element : expected) {
            assertTrue("the XML has " + element, beauti.contains(element));
        }

        assertTrue(treeLime.contains("Generated by TreeLime "));
        beauti = upTo(beauti, "<!-- Define operators");
        treeLime = upTo(treeLime, "<!-- The densities to maximize");
        // the comment is padded to a fixed width, so drop the whole line
        beauti = beauti.replaceFirst("<!-- Generated by BEAUTi [^\n]*\n", "");
        treeLime = treeLime.replaceFirst("<!-- Generated by TreeLime [^\n]*\n", "");

        if (!beauti.equals(treeLime)) {
            List<String> b = Arrays.asList(beauti.split("\n", -1));
            List<String> t = Arrays.asList(treeLime.split("\n", -1));
            int line = 0;
            while (line < Math.min(b.size(), t.size()) && b.get(line).equals(t.get(line))) {
                line++;
            }
            fail("XML differs at line " + (line + 1) + ":\nBEAUti:   " + (line < b.size() ? b.get(line) : "<end>") +
                    "\nTreeLime: " + (line < t.size() ? t.get(line) : "<end>"));
        }
    }

    private static String upTo(String xml, String marker) {
        int end = xml.indexOf(marker);
        assertTrue("the XML has " + marker, end > 0);
        return xml.substring(0, end);
    }

    private static String generate(String app, String data, Step[] steps) throws Exception {

        Class<?> factoryType = Class.forName(app + ".components.ComponentFactory");
        Object components = Array.newInstance(factoryType, COMPONENTS.length);
        for (int i = 0; i < COMPONENTS.length; i++) {
            Array.set(components, i, Class.forName(app + "." + COMPONENTS[i]).getField("INSTANCE").get(null));
        }

        Class<?> optionsType = Class.forName(app + ".options." + (app.equals(BEAUTI) ? "BeautiOptions" : "TreeLimeOptions"));
        Object options = optionsType.getConstructor(components.getClass()).newInstance(components);

        Class<?> importerType = Class.forName(app + ".util." + (app.equals(BEAUTI) ? "BEAUTiImporter" : "TreeLimeImporter"));
        Object importer = twoArgumentConstructor(importerType).newInstance(null, options);
        importerType.getMethod("importFromFile", File.class).invoke(importer, new File(data));

        // TreeLime starts from UPGMA by default and BEAUti from a random tree: compare like with like
        apply(options, new Step("treeModels", "setStartingTreeType", "UPGMA"));
        if (app.equals(TREELIME)) {
            // the model as BEAUti writes it: no pre-order flags for analytic gradients
            Object maximization = get(options, "maximizationOptions");
            Method setMode = method(maximization, "setGradientMode");
            setMode.invoke(maximization, enumValue(setMode.getParameterTypes()[0], "NUMERIC"));
        }
        for (Step step : steps) {
            apply(options, step);
        }

        String stem = "forkIdentity";
        set(options, "fileNameStem", stem);
        set(options, "logFileName", stem + ".log");
        set(options, "chainLength", 10);
        set(options, "logEvery", 10);
        set(options, "echoEvery", 10);
        @SuppressWarnings("unchecked")
        List<String> treeFileNames = (List<String>) get(options, "treeFileName");
        treeFileNames.clear();
        for (Object tree : (List<?>) call(options, "getPartitionTreeModels")) {
            treeFileNames.add(stem + "." + call(tree, "getPrefix") + "trees");
        }
        call(options, "selectParameters");
        call(options, "selectOperators");

        File xml = File.createTempFile("forkIdentity", ".xml");
        xml.deleteOnExit();
        Object generator = Class.forName(app + ".generator.BeastGenerator")
                .getConstructor(optionsType, components.getClass()).newInstance(options, components);
        generator.getClass().getMethod("generateXML", File.class).invoke(generator, xml);
        return new String(Files.readAllBytes(xml.toPath()));
    }

    private static void apply(Object options, Step step) throws Exception {
        switch (step.target) {
            case UNLINK_CLOCKS:
                // as the Data panel's "unlink clock models" does
                for (Object partition : (List<?>) get(options, "dataPartitions")) {
                    Object clock = call(partition, "getPartitionClockModel");
                    String name = (String) call(partition, "getName");
                    if (!call(clock, "getName").equals(name)) {
                        Constructor<?> copy = null;
                        for (Constructor<?> c : clock.getClass().getConstructors()) {
                            if (c.getParameterCount() == 3 && c.getParameterTypes()[1] == String.class) {
                                copy = c;
                            }
                        }
                        clock = copy.newInstance(options, name, clock);
                        method(partition, "setPartitionClockModel").invoke(partition, clock);
                    }
                    method(clock, "setPartitionTreeModel").invoke(clock, call(partition, "getPartitionTreeModel"));
                }
                break;
            case TIP_DATES:
                setTipDatesFromNames(options);
                break;
            default:
                String getter = "get" + Character.toUpperCase(step.target.charAt(0)) + step.target.substring(1);
                getter = getter.replace("getClocks", "getPartitionClockModels")
                        .replace("getTreePriors", "getPartitionTreePriors")
                        .replace("getSubstitutionModels", "getPartitionSubstitutionModels")
                        .replace("getTreeModels", "getPartitionTreeModels");
                for (Object model : (List<?>) call(options, getter)) {
                    Method setter = method(model, step.method);
                    Class<?> type = setter.getParameterTypes()[0];
                    Object value = step.value;
                    if (type.isEnum()) {
                        value = enumValue(type, (String) value);
                    }
                    setter.invoke(model, value);
                }
        }
    }

    // dates from the two-digit year that ends each name (D4Brazi82 is 1982), as the Tip Dates panel would set them
    private static void setTipDatesFromNames(Object options) throws Exception {
        TaxonList taxa = (TaxonList) get(options, "taxonList");
        Date mostRecent = null;
        for (int i = 0; i < taxa.getTaxonCount(); i++) {
            Taxon taxon = taxa.getTaxon(i);
            String name = taxon.getId();
            int year = 1900 + Integer.parseInt(name.substring(name.length() - 2));
            Date date = new Date(year, Units.Type.YEARS, false);
            taxon.setDate(date);
            if (mostRecent == null || date.after(mostRecent)) {
                mostRecent = date;
            }
        }
        set(options, "useTipDates", true);
        double maximumTipHeight = 0.0;
        for (int i = 0; i < taxa.getTaxonCount(); i++) {
            Taxon taxon = taxa.getTaxon(i);
            double height = mostRecent.getTimeValue() - taxon.getDate().getTimeValue();
            taxon.setAttribute("_height", height);
            maximumTipHeight = Math.max(maximumTipHeight, height);
        }
        set(options, "maximumTipHeight", maximumTipHeight);
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    private static Object enumValue(Class<?> type, String name) {
        return Enum.valueOf((Class<? extends Enum>) type, name);
    }

    private static Constructor<?> twoArgumentConstructor(Class<?> type) {
        for (Constructor<?> c : type.getConstructors()) {
            if (c.getParameterCount() == 2) {
                return c;
            }
        }
        throw new IllegalArgumentException("no two-argument constructor in " + type);
    }

    private static Method method(Object target, String name) {
        List<Method> found = new ArrayList<>();
        for (Method m : target.getClass().getMethods()) {
            if (m.getName().equals(name) && m.getParameterCount() == 1) {
                found.add(m);
            }
        }
        if (found.size() != 1) {
            throw new IllegalArgumentException(found.size() + " one-argument methods " + name + " in " + target.getClass());
        }
        return found.get(0);
    }

    private static Object call(Object target, String name) throws Exception {
        return target.getClass().getMethod(name).invoke(target);
    }

    private static Object get(Object target, String field) throws Exception {
        return target.getClass().getField(field).get(target);
    }

    private static void set(Object target, String field, Object value) throws Exception {
        target.getClass().getField(field).set(target, value);
    }
}
